function numberPaths(day) {
  const digits = String(day)
    .split('')
    .map((digit) => glyphs[digit]);
  const gap = digits.length === 1 ? 0 : 5;
  const totalWidth = digits.reduce((sum, glyph) => sum + glyph.width, 0) + gap;
  let x = 54 - totalWidth / 2;

  return digits
    .map((glyph) => {
      const path = `    <path
        android:fillColor="#00000000"
        android:pathData="${glyph.path}"
        android:strokeColor="#2563EB"
        android:strokeLineCap="round"
        android:strokeLineJoin="round"
        android:strokeWidth="4" />`;
      const translated = `    <group android:translateX="${x}" android:translateY="56">\n${path}\n    </group>`;
      x += glyph.width + gap;
      return translated;
    })
    .join('\n');
}

